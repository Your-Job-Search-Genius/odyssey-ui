export interface FileIconProps extends SVGProps<SVGSVGElement> {
    /**
     * The type of file to display the icon for. This can be a specific file type (e.g. "pdf", "docx", "mp4") or a
     * MIME type (e.g. "application/pdf", "video/mp4"). MIME types are categorized into one of: `image`, `code`,
     * `document`, `video`, `audio`, or fall back to `empty` if unrecognized.
     *
     * @default "empty"
     */
    type: FileType;
    /**
     * The variant of the file icon:
     * - `"default"`: colored icons.
     * - `"gray"`: monochrome/gray icons.
     * - `"solid"`: solid color background icons.
     *
     * @default "default"
     */
    variant?: FileIconVariant;
    /**
     * The color theme of the file icon.
     * @default "light"
     */
    theme?: "light" | "dark";
    /**
     * The size of the file icon in pixels.
     * @default 40
     */
    size?: number;
}

/**
 * Displays an icon for a specific file type or MIME type. Supports a wide range of file types and MIME types,
 * falling back to a generic "empty" icon when the type isn't recognized.
 *
 * @example
 * <FileIcon type="pdf" />
 * <FileIcon type="application/pdf" />
 * <FileIcon type="video/mp4" />
 * <FileIcon type="docx" variant="gray" theme="dark" size={32} />
 */
export const FileIcon = ({ type, variant = "default", theme = "light", ...props }: FileIconProps) => {
    const isMimeType = type.includes("/");
    const mimeCategory = isMimeType ? categorizeMimeType(type) : undefined;
    const candidateKey = isMimeType ? type.split("/")[1] : type;

    const key: SupportedFileType =
        candidateKey && isSupportedFileType(candidateKey) ? candidateKey : mimeCategory && isSupportedFileType(mimeCategory) ? mimeCategory : "empty";

    const Icon = ICONS[variant][key] ?? ICONS[variant].empty;

    return <Icon theme={theme} {...props} />;
};
