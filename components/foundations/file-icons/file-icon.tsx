/**
 * Categorizes a MIME type string into one of the predefined categories: `image`, `code`, `document`, `video`,
 * `audio`, or returns `unknown` if the MIME type does not match any known category.
 *
 * @example
 * categorizeMimeType("image/jpeg"); // "image"
 * categorizeMimeType("application/pdf"); // "document"
 * categorizeMimeType("text/html"); // "code"
 */
export const categorizeMimeType = (mimeType: string): MimeTypeCategory => {
    const [type, subtype] = mimeType.split("/");
    if (!type || !subtype) return "unknown";

    switch (type) {
        case "image":
            return "image";
        case "audio":
            return "audio";
        case "video":
            return "video";
        case "application":
        case "text":
            if (MIME_CODE_SUBTYPES.includes(subtype)) return "code";
            if (MIME_DOCUMENT_SUBTYPES.includes(subtype)) return "document";
            break;
    }
    return "unknown";
};

